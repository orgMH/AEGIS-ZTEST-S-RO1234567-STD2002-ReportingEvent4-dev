# ---- 1. データの作成 ----
# 数値ベクトルを作成
x <- c(1, 2, 3, 4, 5)

# データフレームを作成
df <- data.frame(
  value = x,
  squared = x^2
)

# ---- 2. 基本統計量の計算 ----
mean_value <- mean(df$value)     # 平均
sd_value <- sd(df$value)         # 標準偏差
summary(df)                      # 要約統計量

# ---- 3. 簡単なプロット ----
plot(df$value, df$squared,
     main = "値とその二乗の散布図",
     xlab = "Value",
     ylab = "Squared",
     pch = 19, col = "blue")